// rendering
// ─────────────────────────────────────────────────────────────────────────────

function renderApiSurface(routes: Route[]): string {
  const byFile = new Map<string, Route[]>();
  for (const r of routes) {
    if (!byFile.has(r.file)) byFile.set(r.file, []);
    byFile.get(r.file)!.push(r);
  }

  const lines = [
    BANNER,
    '',
    '# API surface',
    '',
    `**${routes.length} routes** across ${byFile.size} controllers. Base path \`/v1\` (set in \`main.ts\`).`,
    '',
    'Extracted from `@Controller` / `@Get` / `@Post` / `@Put` / `@Delete` / `@Patch` decorators.',
    'Request and response schemas are not captured — run the app and read Swagger at `/api` for those.',
    '',
    'The `Roles` column shows `@Roles(...)` found on the class or method. `—` means no role',
    'decorator; it does **not** mean the route is public — `auth.guard.ts` applies separately.',
    '',
  ];

  for (const file of [...byFile.keys()].sort()) {
    lines.push(`## \`${file}\``, '');
    lines.push('| Method | Route | Handler | Roles |', '|---|---|---|---|');
    for (const r of byFile.get(file)!) {
      lines.push(`| ${r.method} | \`${r.route}\` | \`${r.handler}\` | ${r.roles} |`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

function renderContracts(): string {
  const lines = [BANNER, '', '# Contracts', '', 'Load-bearing declarations, copied from source.', ''];

  const mirror = compareLanguageMirror();
  lines.push('## Language mirror', '');
  lines.push(
    mirror.inSync
      ? `**In sync** — ${mirror.backend.length} languages on both sides: \`${mirror.backend.join(', ')}\``
      : `**OUT OF SYNC** — backend \`${mirror.backend.join(', ')}\` vs frontend \`${mirror.frontend.join(', ')}\``,
  );
  lines.push(
    '',
    'Sources: `backend/src/services/bulk-ingest.service.ts` → `SUPPORTED_LANGUAGES`,',
    '`frontend/src/types/index.ts` → `Language`.',
    '',
  );

  for (const { file, symbols } of CONTRACTS) {
    const abs = path.join(BACKEND, file);
    if (!fs.existsSync(abs)) {
      lines.push(`## \`${file}\``, '', '**File not found.**', '');
      continue;
    }
    const sf = parse(abs);
    lines.push(`## \`backend/${file}\``, '');
    for (const sym of [...symbols].sort()) {
      const text = findDeclaration(sf, sym);
      lines.push(`### \`${sym}\``, '');
      lines.push(text ? '```typescript\n' + text + '\n```' : '**Not found in this file.**');
      lines.push('');
    }
  }

  lines.push('## Mongoose schemas', '');
  for (const s of extractSchemas()) {
    lines.push(`### \`${s.cls}\` — \`backend/${s.file}\``, '');
    lines.push(
      s.fields.length
        ? s.fields.map((f) => `- \`${f}\``).join('\n')
        : '_no `@Prop()` fields found_',
    );
    lines.push('');
  }

  return lines.join('\n');
}

// ─────────────────────────────────────────────────────────────────────────────
// reference checking — do the docs still point at things that exist?
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Paths cited in docs that are known-absent on purpose — each is documented in the repo as
 * broken or deleted, so citing it is correct and must not fail the check.
 */
const EXPECTED_MISSING = new Set([
  'src/scripts/bulk_ingest.ts',
  'backend/src/scripts/bulk_ingest.ts',
  'docs/AI_CONTEXT_BULK_UPLOAD.md',
  'docs/FRONTEND_BULK_UPLOAD_ARCHITECTURE.md',
  'docs/context.md',
  'AI_CONTEXT_BULK_UPLOAD.md',
  'FRONTEND_BULK_UPLOAD_ARCHITECTURE.md',
]);

/**
 * Docs excluded from reference checking.
 *
 * `docs/superpowers/` holds design specs, which by their nature discuss files that do not
 * exist yet (planned work), files that were deliberately never created, and files outside the
 * repo entirely. Checking them produces only noise. What must stay true is the documentation
 * agents read as *fact* — CLAUDE.md, docs/decisions/, docs/invariants.md.
 */
const UNCHECKED_DOC_DIRS = ['docs/superpowers'];

const IGNORED_DIRS = new Set(['node_modules', '.git', 'dist', 'coverage']);

/** Every file in the repo, indexed once: by repo-relative path and by bare filename. */
let fileIndex: { paths: Set<string>; names: Set<string> } | null = null;

function indexRepo(): { paths: Set<string>; names: Set<string> } {
  if (fileIndex) return fileIndex;
  const paths = new Set<string>();
  const names = new Set<string>();
  const stack = [REPO];
  while (stack.length) {
    const dir = stack.pop()!;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (IGNORED_DIRS.has(e.name)) continue;
      const abs = path.join(dir, e.name);
      if (e.isDirectory()) stack.push(abs);
      else {
        paths.add(path.relative(REPO, abs).split(path.sep).join('/'));
        names.add(e.name);
      }
    }
  }
  fileIndex = { paths, names };
  return fileIndex;
}

/** Every symbol-ish token appearing in the source trees, indexed once. */
let symbolIndex: Set<string> | null = null;

function indexSymbols(): Set<string> {
  if (symbolIndex) return symbolIndex;
  const found = new Set<string>();
  const stack = [path.join(REPO, 'backend/src'), path.join(REPO, 'frontend/src')];
  while (stack.length) {
    const dir = stack.pop()!;
    if (!fs.existsSync(dir)) continue;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (IGNORED_DIRS.has(e.name)) continue;
      const abs = path.join(dir, e.name);
      if (e.isDirectory()) stack.push(abs);
      else if (/\.(ts|tsx)$/.test(e.name)) {
        for (const tok of fs.readFileSync(abs, 'utf8').match(/[A-Za-z_][A-Za-z0-9_]*/g) ?? [])
          found.add(tok);
      }
    }
  }
  symbolIndex = found;
  return symbolIndex;
}

function docFiles(): string[] {
  const out: string[] = [];
  const claude = path.join(REPO, 'CLAUDE.md');
  if (fs.existsSync(claude)) out.push(claude);

  const walk = (dir: string) => {
    if (!fs.existsSync(dir)) return;
    for (const e of fs
      .readdirSync(dir, { withFileTypes: true })
      .sort((a, b) => a.name.localeCompare(b.name))) {
      const p = path.join(dir, e.name);
      const rel = path.relative(REPO, p).split(path.sep).join('/');
      if (UNCHECKED_DOC_DIRS.some((d) => rel.startsWith(d))) continue;
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.md') && !rel.startsWith('docs/generated')) out.push(p);
    }
  };
  walk(path.join(REPO, 'docs'));
  return out;
}

/** A citation resolves if it matches a repo-relative path, or is a bare filename that exists. */
function resolveCited(p: string): boolean {
  const { paths, names } = indexRepo();
  const norm = p.replace(/^\.\//, '');
  if (paths.has(norm)) return true;
  for (const prefix of ['backend/', 'backend/src/', 'frontend/', 'docs/']) {
    if (paths.has(prefix + norm)) return true;
  }
  for (const known of paths) {
    if (known.endsWith('/' + norm)) return true;
  }
  return names.has(path.basename(norm));
}

function checkReferences(): string[] {
  const problems: string[] = [];
  const pathRe = /`([A-Za-z0-9_./-]+\.(?:ts|tsx|md|json|example|yml))`/g;
  const symRe = /→ `([A-Za-z_][A-Za-z0-9_]*)`/g;
  const symbols = indexSymbols();

  for (const doc of docFiles()) {
    const text = fs.readFileSync(doc, 'utf8');
    const rel = path.relative(REPO, doc).split(path.sep).join('/');

    for (const m of text.matchAll(pathRe)) {
      const cited = m[1];
      if (EXPECTED_MISSING.has(cited)) continue;
      if (resolveCited(cited)) continue;
      // A leading dot with no directory part and no match on disk is prose naming a file
      // *extension* (".spec.ts", ".d.ts"), not a path. Real dotfiles such as ".env.example"
      // resolve above and never reach here.
      if (cited.startsWith('.') && !cited.includes('/')) continue;
      problems.push(`${rel}: path does not exist — \`${cited}\``);
    }

    for (const m of text.matchAll(symRe)) {
      if (!symbols.has(m[1]))
        problems.push(`${rel}: symbol not found in source — \`${m[1]}\``);
    }
  }

  return [...new Set(problems)].sort();
}

// ─────────────────────────────────────────────────────────────────────────────
// main
// ─────────────────────────────────────────────────────────────────────────────

function build(): Record<string, string> {
  return {
    'api-surface.md': renderApiSurface(extractRoutes()),
    'contracts.md': renderContracts(),
  };
}

function main() {
  const check = process.argv.includes('--check');
  const built = build();
  let failed = false;

  if (check) {
    for (const [name, content] of Object.entries(built)) {
      const abs = path.join(OUT_DIR, name);
      if (!fs.existsSync(abs)) {
        console.error(`STALE  docs/generated/${name} is missing`);
        failed = true;
      } else if (fs.readFileSync(abs, 'utf8') !== content) {
        console.error(`STALE  docs/generated/${name} does not match source`);
        failed = true;
      } else {
        console.log(`ok     docs/generated/${name}`);
      }
    }

    const problems = checkReferences();
    if (problems.length) {
      console.error(`\nBroken references (${problems.length}):`);
      for (const p of problems) console.error(`  ${p}`);
      failed = true;
    } else {
      console.log('ok     all cited paths and symbols resolve');
    }

    const mirror = compareLanguageMirror();
    if (!mirror.inSync) {
      console.error(
        `\nLanguage mirror OUT OF SYNC: backend [${mirror.backend}] vs frontend [${mirror.frontend}]`,
      );
      failed = true;
    } else {
      console.log('ok     language mirror in sync');
    }

    if (failed) {
      console.error('\nRun `npm run context:generate` and commit the result.');
      process.exit(1);
    }
    console.log('\ncontext:check passed');
    return;
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const [name, content] of Object.entries(built)) {
    fs.writeFileSync(path.join(OUT_DIR, name), content);
    console.log(`wrote  docs/generated/${name}`);
  }

  const problems = checkReferences();
  if (problems.length) {
    console.log(`\nnote: ${problems.length} broken doc reference(s) — not fatal here, fatal in check:`);
    for (const p of problems) console.log(`  ${p}`);
  }
}

main();
