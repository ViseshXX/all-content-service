/**
 * Context generator — writes docs/generated/ from the source of truth.
 *
 *   npm run context:generate    write the files
 *   npm run context:check       verify they match source; exit 1 if not
 *
 * Why this exists: hand-written docs in this repo drifted badly. Three files gave three
 * different answers for SUPPORTED_LANGUAGES and none matched the code. Anything mechanically
 * derivable from source is generated here instead of typed by hand.
 *
 * Why static parsing rather than the Swagger document:
 * app.module.ts uses MongooseModule.forRootAsync, so booting Nest to read
 * SwaggerModule.createDocument requires a live MongoDB. That makes it useless in CI and on a
 * machine without the dev database. Parsing the decorators with the TypeScript compiler API
 * needs no runtime and always works. Cost: no request/response schemas, only the route surface.
 *
 * Output is deterministic — files and symbols are sorted — so diffs stay reviewable.
 */
import * as fs from 'fs';
import * as path from 'path';
import * as ts from 'typescript';

const BACKEND = path.resolve(__dirname, '..');
const REPO = path.resolve(BACKEND, '..');
const OUT_DIR = path.join(REPO, 'docs', 'generated');
const BANNER =
  '<!-- GENERATED by `npm run context:generate` (backend/scripts/generate-context.ts) — do not edit by hand -->';

const HTTP_DECORATORS = ['Get', 'Post', 'Put', 'Delete', 'Patch'];

/** Declarations copied verbatim into contracts.md, by file. */
const CONTRACTS: { file: string; symbols: string[] }[] = [
  {
    file: 'src/services/bulk-ingest.service.ts',
    symbols: [
      'SUPPORTED_LANGUAGES',
      'LANGUAGE_NORMALIZE_MAP',
      'TemplateType',
      'TemplateConfig',
      'TEMPLATE_CONFIGS',
      'WizardConfig',
    ],
  },
  {
    file: 'src/services/bulk-processor.service.ts',
    symbols: [
      'STORAGE_DIR',
      'MAX_ROWS',
      'S3_BUCKET',
      'STALE_CUTOFF_MS',
      'RESUME_COOLDOWN_MS',
      'M1M2_ENGLISH_REGEX',
      'M1M2_SCRIPT_REGEXES',
      'M1M2_ML_COL',
    ],
  },
  { file: 'src/services/asset-pipeline.service.ts', symbols: ['S3_BUCKET'] },
];

const SCHEMA_DIR = 'src/schemas';

// ─────────────────────────────────────────────────────────────────────────────
// helpers
// ─────────────────────────────────────────────────────────────────────────────

function parse(absPath: string): ts.SourceFile {
  return ts.createSourceFile(
    absPath,
    fs.readFileSync(absPath, 'utf8'),
    ts.ScriptTarget.Latest,
    true,
  );
}

function decoratorsOf(node: ts.Node): ts.Decorator[] {
  return (ts.canHaveDecorators(node) ? ts.getDecorators(node) : undefined)?.slice() ?? [];
}

/** `@Foo('bar')` → { name: 'Foo', args: ["'bar'"] } */
function readDecorator(d: ts.Decorator): { name: string; args: string[] } | null {
  const expr = d.expression;
  if (!ts.isCallExpression(expr) || !ts.isIdentifier(expr.expression)) return null;
  return {
    name: expr.expression.text,
    args: expr.arguments.map((a) => a.getText()),
  };
}

function stripQuotes(s: string): string {
  return s.replace(/^['"`]|['"`]$/g, '');
}

function joinRoute(base: string, sub: string): string {
  const b = stripQuotes(base).replace(/^\/|\/$/g, '');
  const s = stripQuotes(sub).replace(/^\/|\/$/g, '');
  return '/v1/' + [b, s].filter(Boolean).join('/');
}

function listFiles(relDir: string, suffix = '.ts'): string[] {
  const abs = path.join(BACKEND, relDir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs)
    .filter((f) => f.endsWith(suffix) && !f.endsWith('.spec.ts'))
    .sort()
    .map((f) => path.join(relDir, f));
}

// ─────────────────────────────────────────────────────────────────────────────
// routes
// ─────────────────────────────────────────────────────────────────────────────

type Route = {
  method: string;
  route: string;
  handler: string;
  file: string;
  roles: string;
};

function extractRoutes(): Route[] {
  const files = [...listFiles('src/controllers'), 'src/app.controller.ts'].filter((f) =>
    fs.existsSync(path.join(BACKEND, f)),
  );

  const routes: Route[] = [];

  for (const rel of files.sort()) {
    const sf = parse(path.join(BACKEND, rel));

    sf.forEachChild((node) => {
      if (!ts.isClassDeclaration(node)) return;

      const ctrl = decoratorsOf(node)
        .map(readDecorator)
        .find((d) => d?.name === 'Controller');
      if (!ctrl) return;

      const base = ctrl.args[0] ?? '';
      const classRoles = decoratorsOf(node)
        .map(readDecorator)
        .filter((d) => d?.name === 'Roles')
        .flatMap((d) => d!.args.map(stripQuotes));

      for (const member of node.members) {
        if (!ts.isMethodDeclaration(member)) continue;
        const decs = decoratorsOf(member).map(readDecorator);

        const http = decs.find((d) => d && HTTP_DECORATORS.includes(d.name));
        if (!http) continue;

        const methodRoles = decs
          .filter((d) => d?.name === 'Roles')
          .flatMap((d) => d!.args.map(stripQuotes));
        const roles = [...new Set([...classRoles, ...methodRoles])];

        routes.push({
          method: http.name.toUpperCase(),
          route: joinRoute(base, http.args[0] ?? ''),
          handler: member.name.getText(),
          file: rel,
          roles: roles.length ? roles.join(', ') : '—',
        });
      }
    });
  }

  return routes.sort(
    (a, b) => a.route.localeCompare(b.route) || a.method.localeCompare(b.method),
  );
}

// ─────────────────────────────────────────────────────────────────────────────
// contracts
// ─────────────────────────────────────────────────────────────────────────────

/** Find a top-level declaration by name and return its source text. */
function findDeclaration(sf: ts.SourceFile, name: string): string | null {
  let out: string | null = null;

  const visit = (node: ts.Node) => {
    if (out) return;
    if (
      (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) &&
      node.name.text === name
    ) {
      out = node.getText();
      return;
    }
    if (ts.isVariableStatement(node)) {
      for (const d of node.declarationList.declarations) {
        if (ts.isIdentifier(d.name) && d.name.text === name) {
          out = node.getText();
          return;
        }
      }
    }
    ts.forEachChild(node, visit);
  };

  ts.forEachChild(sf, visit);
  return out;
}

/** Mongoose schema classes → their @Prop-decorated field names and declared types. */
function extractSchemas(): { file: string; cls: string; fields: string[] }[] {
  const out: { file: string; cls: string; fields: string[] }[] = [];

  for (const rel of listFiles(SCHEMA_DIR)) {
    const sf = parse(path.join(BACKEND, rel));

    sf.forEachChild((node) => {
      if (!ts.isClassDeclaration(node) || !node.name) return;
      const isSchema = decoratorsOf(node)
        .map(readDecorator)
        .some((d) => d?.name === 'Schema');
      if (!isSchema) return;

      const fields: string[] = [];
      for (const m of node.members) {
        if (!ts.isPropertyDeclaration(m)) continue;
        const hasProp = decoratorsOf(m)
          .map(readDecorator)
          .some((d) => d?.name === 'Prop');
        if (!hasProp) continue;
        const optional = m.questionToken ? '?' : '';
        const type = m.type ? m.type.getText().replace(/\s+/g, ' ') : 'unknown';
        fields.push(`${m.name.getText()}${optional}: ${type}`);
      }

      out.push({ file: rel, cls: node.name.text, fields });
    });
  }

  return out.sort((a, b) => a.cls.localeCompare(b.cls));
}

/**
 * The coupling that actually broke: the backend language list and the frontend Language
 * union must agree. Compared here so a mismatch shows up in the generated output.
 */
function compareLanguageMirror(): { backend: string[]; frontend: string[]; inSync: boolean } {
  const beSrc = fs.readFileSync(
    path.join(BACKEND, 'src/services/bulk-ingest.service.ts'),
    'utf8',
  );
  const beMatch = beSrc.match(/SUPPORTED_LANGUAGES\s*=\s*\[([^\]]*)\]/);
  const backend = (beMatch?.[1] ?? '')
    .split(',')
    .map((s) => stripQuotes(s.trim()))
    .filter(Boolean)
    .sort();

  const fePath = path.join(REPO, 'frontend/src/types/index.ts');
  let frontend: string[] = [];
  if (fs.existsSync(fePath)) {
    const feMatch = fs
      .readFileSync(fePath, 'utf8')
      .match(/export type Language\s*=\s*([^\n]+)/);
    frontend = (feMatch?.[1] ?? '')
      .split('|')
      .map((s) => stripQuotes(s.trim().replace(/;$/, '')))
      .filter(Boolean)
      .sort();
  }

  return {
    backend,
    frontend,
    inSync: backend.length > 0 && backend.join(',') === frontend.join(','),
  };
}

